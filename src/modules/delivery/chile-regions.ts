export const CHILE_REGION_NAMES = Object.keys(CHILE_REGION_COMMUNES);

export function findChileCommunes(regionName: string): string[] | null {
  const normalized = regionName.trim().toLowerCase();
  const entry = Object.entries(CHILE_REGION_COMMUNES).find(
    ([name]) => name.toLowerCase() === normalized
  );
  if (entry) return entry[1];
  const partial = Object.entries(CHILE_REGION_COMMUNES).find(([name]) =>
    name.toLowerCase().includes(normalized) || normalized.includes(name.toLowerCase())
  );
  return partial?.[1] ?? null;
}
